# MESSAGE HANDLER LAYER  (transformation + serialization stages)
# =====================================================================
def S(parent, tag, txt=None):
    e = etree.SubElement(parent, f"{{{NS}}}{tag}")
    if txt is not None:
        e.text = str(txt)
    return e

def build_tree(platform, mp, mid):
    """
    Transformation stage: transforms an extracted native UAV message
    into its NDIEM XML representation (an in-memory element tree).
    Excludes serialization and validation.
    """
    i = INFO[platform]
    root = etree.Element(f"{{{NS}}}NDIEMMessage", nsmap=NSMAP)
    S(root, "messageID", mid); S(root, "timestamp", "2025-01-01T00:00:00")
    h = S(root, "Header"); S(h, "senderID", platform); S(h, "receiverID", "GCS")
    idn = S(root, "UavIdentificationData")
    S(idn, "uavID", i[0]); S(idn, "uavManufacturer", i[1])
    S(idn, "uavModel", i[2]); S(idn, "uavType", i[3])
    ori = all(k in mp for k in ("roll", "pitch", "yaw"))
    vel = all(k in mp for k in ("vx", "vy", "vz"))
    pos = any(k in mp for k in ("lat", "lon", "alt"))
    bat = "battery_pct" in mp
    if ori or vel or pos or bat:
        tel = S(root, "UavTelemetryData")
        S(tel, "telemetryTimestamp", "2025-01-01T00:00:00"); S(tel, "status", "OK")
        if bat:
            b = S(tel, "UavBattery")
            S(b, "chargeValue", mp.get("battery_voltage", mp["battery_pct"]))
            S(b, "chargePercent", int(mp["battery_pct"]))
        if ori:
            o = S(tel, "UavOrientation")
            S(o, "pitch", mp["pitch"]); S(o, "yaw", mp["yaw"]); S(o, "roll", mp["roll"])
        if vel:
            v = S(tel, "UavVelocity")
            S(v, "vx", mp["vx"]); S(v, "vy", mp["vy"]); S(v, "vz", mp["vz"])
        if pos:
            ps = S(tel, "UavPosition")
            S(ps, "lat", mp.get("lat", 0.0)); S(ps, "lon", mp.get("lon", 0.0))
            S(ps, "alt", mp.get("alt", 0.0))
    return root                       # returns the TREE, not bytes

def serialize(root):
    """Serialization stage: XML tree -> byte string."""
    return etree.tostring(root)

def build(platform, mp, mid):
    """Transform + serialize, for callers that need bytes."""
    return serialize(build_tree(platform, mp, mid))

# =====================================================================
# RECEIVER / GCS  (parse and consume NDIEM messages)
# =====================================================================
def parse(xb):
    root = etree.fromstring(xb); out = {}
    for el in root.iter():
        tag = etree.QName(el).localname
        if el.text and el.text.strip():
            out[tag] = el.text.strip()
    return out

def receiver_can_consume(parsed, truth, cfg):
    if cfg == "no_xml_schema":
        return False
    exp = list(truth.keys())
    return bool(exp) and all(NDIEM_ELEMENT.get(k, k) in parsed for k in exp)

def match(pv, sv):
    if pv is None:
        return False
    try:
        return abs(float(pv) - float(sv)) < 1e-6
    except (ValueError, TypeError):
        return str(pv) == str(sv)

# =====================================================================
# FAULT MODEL  (emulates link corruption; NOT from the drones)
# =====================================================================
def inject(mp, rng):
    ks = list(mp.keys())
    if not ks:
        return dict(mp), None
    f = rng.choice(ks); out = dict(mp); k = rng.choice(["trunc", "corrupt", "range"])
    if k == "trunc":
        del out[f]
    elif k == "corrupt":
        out[f] = "##BAD##"
    else:
        out[f] = VALID_RANGE.get(f, (-1e6, 1e6))[1] * 1000
    return out, f

def corrupt_map(mp):
    ks = list(mp.keys())
    if len(ks) < 2:
        return dict(mp)
    vs = [mp[k] for k in ks]
    return dict(zip(ks, vs[-1:] + vs[:-1]))

