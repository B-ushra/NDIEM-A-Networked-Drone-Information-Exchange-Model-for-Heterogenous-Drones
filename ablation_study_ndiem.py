def extract(text):
    """Recover every balanced {...} block that follows a [n/N] marker or contains telemetry."""
    records, depth, start = [], 0, None
    for i, ch in enumerate(text):
        if ch == '{':
            if depth == 0: start = i
            depth += 1
        elif ch == '}':
            if depth > 0:
                depth -= 1
                if depth == 0 and start is not None:
                    blob = text[start:i+1]
                    # python-dict style (single quotes) -> JSON
                    try:
                        d = json.loads(blob)
                    except json.JSONDecodeError:
                        try:
                            d = json.loads(blob.replace("'", '"'))
                        except json.JSONDecodeError:
                            start = None; continue
                    records.append(d)
                    start = None
    return records

